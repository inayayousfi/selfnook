// composeDir holds each app's fragment and build files, written from the program.
const composeDir = "compose"

// writeCompose writes every active app's Compose files under compose/<app>/
// and the compose.yaml that includes them, so docker compose runs from Root.
// It removes every other file under compose/, such as the files of an app no
// longer active. The fragments read saved values from the environment of the
// runtime's commands, so no generated file holds a secret.
func (ses *session) writeCompose() error {
	if err := ses.assignAddresses(); err != nil {
		return err
	}
	data := ses.contributions()
	var main strings.Builder
	main.WriteString("# Generated by " + Command + ". Changes here are overwritten.\n")
	main.WriteString("name: " + runtime.Project + "\n\ninclude:\n")
	written := map[string]bool{}
	for _, a := range ses.active() {
		if a.Compose == nil {
			continue
		}
		target := filepath.Join(ses.Root, composeDir, a.Name)
		if err := writeAppFiles(a.Compose, target, app.FragmentData{ComposeData: data, Values: app.ValuesFor(ses.saved, a)}, written); err != nil {
			return fmt.Errorf("Cannot write the %s Compose files: %w", a.Name, err)
		}
		written[filepath.Join(target, addressFile)] = true
		if _, err := files.WriteIfChanged(filepath.Join(target, addressFile), ses.addressFragment(a)); err != nil {
			return fmt.Errorf("Cannot write the %s Compose files: %w", a.Name, err)
		}
		fmt.Fprintf(&main, "  - path:\n      - %[1]s/%[2]s/compose.yaml\n      - %[1]s/%[2]s/%[3]s\n    project_directory: .\n", composeDir, a.Name, addressFile)
	}
	fmt.Fprintf(&main, "\nnetworks:\n  default:\n    name: %s\n    ipam:\n      config:\n        - subnet: %s\n          ip_range: %s\n", runtime.Project, runtime.NetworkSubnet, runtime.AutomaticRange)
	if err := removeUnwritten(filepath.Join(ses.Root, composeDir), written); err != nil {
		return fmt.Errorf("Cannot remove old Compose files: %w", err)
	}
	_, err := files.WriteIfChanged(filepath.Join(ses.Root, "compose.yaml"), []byte(main.String()))
	return err
}

// removeUnwritten removes every file under dir that written does not list,
// then every folder left empty.
func removeUnwritten(dir string, written map[string]bool) error {
	var folders []string
	err := filepath.WalkDir(dir, func(path string, entry fs.DirEntry, err error) error {
		switch {
		case err != nil:
			return err
		case entry.IsDir():
			folders = append(folders, path)
			return nil
		case written[path]:
			return nil
		}
		return os.Remove(path)
	})
	if err != nil {
		return err
	}
	// Deeper folders come later in the walk, so they are removed first.
	for _, folder := range slices.Backward(folders[1:]) {
		entries, err := os.ReadDir(folder)
		if err != nil {
			return err
		}
		if len(entries) == 0 {
			if err := os.Remove(folder); err != nil {
				return err
			}
		}
	}
	return nil
}

// writeAppFiles copies source to target, rendering compose.yaml with data,
// and adds each file it writes to written.
func writeAppFiles(source fs.FS, target string, data app.FragmentData, written map[string]bool) error {
	return fs.WalkDir(source, ".", func(name string, entry fs.DirEntry, err error) error {
		if err != nil || entry.IsDir() {
			return err
		}
		content, err := fs.ReadFile(source, name)
		if err != nil {
			return err
		}
		if name == "compose.yaml" {
			if content, err = renderFragment(content, data); err != nil {
				return err
			}
		}
		path := filepath.Join(target, filepath.FromSlash(name))
		written[path] = true
		_, err = files.WriteIfChanged(path, content)
		return err
	})
}

// renderFragment renders one compose.yaml with the shared template available.
func renderFragment(content []byte, data app.FragmentData) ([]byte, error) {
	tmpl, err := template.New("compose.yaml").Option("missingkey=error").Parse(app.SharedTemplate)
	if err != nil {
		return nil, err
	}
	if tmpl, err = tmpl.Parse(string(content)); err != nil {
		return nil, err
	}
	var rendered bytes.Buffer
	if err := tmpl.Execute(&rendered, data); err != nil {
		return nil, err
	}
	return rendered.Bytes(), nil
}
