package stack

import (
	"errors"
	"fmt"
	"net/netip"
	"slices"
	"strings"

	"github.com/inayayousfi/selfnook/internal/app"
	"github.com/inayayousfi/selfnook/internal/runtime"
)

// addressFile is merged into each app's Compose file and gives every
// container of the app its fixed address. Docker Desktop can restore port
// forwards to the addresses containers had before its engine restarted, so
// an address that never changes keeps those forwards on the right container.
const addressFile = "addresses.yaml"

// addressed lists the services of a that join the stack network themselves.
// Services behind the VPN share the gateway's network and address.
func (ses *session) addressed(a *app.App) []string {
	if a.Services == nil {
		return nil
	}
	var services []string
	for _, service := range a.Services(app.ValuesFor(ses.saved, a)) {
		if !slices.Contains(a.BehindVPN, service) {
			services = append(services, service)
		}
	}
	return services
}

// assignAddresses gives each active service without a saved address the
// lowest free fixed address, in registry order, and saves the result. A saved
// address never changes, so a container keeps it across starts and updates.
func (ses *session) assignAddresses() error {
	subnet := netip.MustParsePrefix(runtime.NetworkSubnet)
	automatic := netip.MustParsePrefix(runtime.AutomaticRange)
	taken := map[netip.Addr]bool{}
	for service, saved := range ses.saved.Addresses {
		address, err := netip.ParseAddr(saved)
		if err != nil || !subnet.Contains(address) || automatic.Contains(address) || taken[address] {
			delete(ses.saved.Addresses, service)
			continue
		}
		taken[address] = true
	}
	changed := false
	// The first address names the network and the second is Docker's gateway.
	next := subnet.Addr().Next().Next()
	for _, a := range ses.active() {
		for _, service := range ses.addressed(a) {
			if _, ok := ses.saved.Addresses[service]; ok {
				continue
			}
			for taken[next] {
				next = next.Next()
			}
			if automatic.Contains(next) || !subnet.Contains(next) {
				return errors.New("The stack network has no free fixed address left.")
			}
			taken[next] = true
			ses.saved.Addresses[service] = next.String()
			changed = true
		}
	}
	if !changed {
		return nil
	}
	return ses.save()
}

// addressFragment is the Compose file that sets the fixed address of each
// service of a.
func (ses *session) addressFragment(a *app.App) []byte {
	var out strings.Builder
	out.WriteString("# Generated by " + Command + ". Changes here are overwritten.\n")
	services := ses.addressed(a)
	if len(services) == 0 {
		out.WriteString("services: {}\n")
		return []byte(out.String())
	}
	out.WriteString("services:\n")
	for _, service := range services {
		fmt.Fprintf(&out, "  %s:\n    networks:\n      default:\n        ipv4_address: %s\n", service, ses.saved.Addresses[service])
	}
	return []byte(out.String())
}
